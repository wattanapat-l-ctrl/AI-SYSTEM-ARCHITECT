export function generateCostDoc(
  project: ProjectSummary,
  cost: CostBreakdown,
  insights: string[],
): string {
  const out: string[] = [];
  out.push(`# ${project.name} \u2014 Infrastructure Cost Model`);
  out.push(``);
  out.push(`> Generated by AI System Architect on ${formatDate(new Date().toISOString())}`);
  out.push(``);

  out.push(`## Summary`);
  out.push(``);
  out.push(
    table(
      ["Metric", "Value"],
      [
        ["Monthly run rate", formatCurrency(cost.monthlyTotal)],
        ["Annual projection", formatCurrency(cost.annualTotal)],
        ["Services tracked", String(cost.lines.length)],
        ["Distinct categories", String(cost.byCategory.length)],
      ],
    ),
  );
  out.push(``);

  out.push(`## Cost by category`);
  out.push(``);
  out.push(
    table(
      ["Category", "Monthly", "Share"],
      cost.byCategory.map((c) => [
        SERVICE_CATEGORY_MAP[c.category as keyof typeof SERVICE_CATEGORY_MAP] ?? c.category,
        formatCurrency(c.monthly),
        `${c.share.toFixed(1)}%`,
      ]),
    ),
  );
  out.push(``);

  out.push(`## Line items`);
  out.push(``);
  out.push(
    table(
      ["Service", "Vendor", "Qty", "Unit", "Unit price", "Monthly", "Annual"],
      cost.lines.map((l) => [
        l.name,
        safe(l.vendor),
        String(l.quantity),
        l.unit,
        formatCurrency(l.unitPrice),
        formatCurrency(l.monthly),
        formatCurrency(l.annual),
      ]),
    ),
  );
  out.push(``);

  if (cost.assumptions.length > 0) {
    out.push(`## Assumptions`);
    out.push(``);
    for (const a of cost.assumptions) out.push(`- ${a}`);
    out.push(``);
  }

  if (insights.length > 0) {
    out.push(`## Observations`);
    out.push(``);
    for (const i of insights) out.push(`- ${i}`);
    out.push(``);
  }

  out.push(`---`);
  out.push(``);
  out.push(
    `_Estimates exclude taxes, support plans, committed-use discounts and egress overages. Validate against your provider's calculator before budgeting._`,
  );

  return out.join("\n");
}


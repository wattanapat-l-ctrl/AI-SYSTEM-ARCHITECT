export function generateApiDoc(spec: ApiSpec, endpoints: ApiEndpoint[]): string {
  const out: string[] = [];
  const groups = new Map<string, ApiEndpoint[]>();
  for (const e of endpoints) {
    groups.set(e.group_name || "default", [...(groups.get(e.group_name || "default") ?? []), e]);
  }

  out.push(`# ${spec.name} \u2014 API Reference`);
  out.push(``);
  out.push(`> Generated by AI System Architect on ${formatDate(new Date().toISOString())}`);
  out.push(``);
  if (spec.description) {
    out.push(spec.description);
    out.push(``);
  }
  out.push(
    table(
      ["Field", "Value"],
      [
        ["Version", spec.version],
        ["Base URL", spec.base_url],
        ["Endpoints", String(endpoints.length)],
        ["Authentication", [...new Set(endpoints.map((e) => e.auth_type))].join(", ") || "none"],
      ],
    ),
  );
  out.push(``);
  out.push(`## Endpoint summary`);
  out.push(``);
  out.push(
    table(
      ["Method", "Path", "Group", "Auth", "Summary"],
      endpoints.map((e) => [
        e.method.toUpperCase(),
        `\`${e.path}\``,
        safe(e.group_name),
        AUTH_TYPES.find((a) => a.id === e.auth_type)?.label ?? e.auth_type,
        safe(e.summary),
      ]),
    ),
  );
  out.push(``);

  out.push(`## Endpoints`);
  out.push(``);
  for (const [group, groupEndpoints] of groups) {
    out.push(`### ${group}`);
    out.push(``);
    for (const e of groupEndpoints) {
      out.push(`#### \`${e.method.toUpperCase()} ${e.path}\``);
      out.push(``);
      if (e.is_deprecated) {
        out.push(`> **Deprecated.**`);
        out.push(``);
      }
      if (e.summary) {
        out.push(e.summary);
        out.push(``);
      }
      if (e.description) {
        out.push(e.description);
        out.push(``);
      }
      out.push(
        table(
          ["Property", "Value"],
          [
            ["Operation ID", safe(e.operation_id)],
            ["Auth", AUTH_TYPES.find((a) => a.id === e.auth_type)?.label ?? e.auth_type],
            ["Rate limit", safe(e.rate_limit)],
            ["Tags", (e.tags ?? []).join(", ") || "\u2014"],
          ],
        ),
      );
      out.push(``);

      if ((e.params ?? []).length > 0) {
        out.push(`**Parameters**`);
        out.push(``);
        out.push(
          table(
            ["Name", "In", "Type", "Required", "Description"],
            e.params.map((p) => [p.name, p.in, p.type, p.required ? "yes" : "no", safe(p.description, "")]),
          ),
        );
        out.push(``);
      }

      if (e.request_body) {
        out.push(`**Request body**`);
        out.push(``);
        out.push("```json");
        out.push(JSON.stringify(e.request_body, null, 2));
        out.push("```");
        out.push(``);
      }

      out.push(`**Responses**`);
      out.push(``);
      const responseEntries = Object.entries(e.responses ?? {});
      if (responseEntries.length === 0) {
        out.push(`_No responses defined._`);
      } else {
        out.push(
          table(
            ["Status", "Description"],
            responseEntries.map(([status, value]) => [
              status,
              safe((value as Record<string, unknown>)?.description as string),
            ]),
          ),
        );
      }
      out.push(``);

      if ((e.errors ?? []).length > 0) {
        out.push(`**Errors**`);
        out.push(``);
        out.push(
          table(
            ["HTTP", "Code", "Description"],
            e.errors.map((err) => [String(err.httpStatus), err.code, err.description]),
          ),
        );
        out.push(``);
      }

      out.push(
        `\`\`\`bash\ncurl -X ${e.method.toUpperCase()} '${spec.base_url.replace(/\/$/, "")}${e.path}' \\\n  -H 'Accept: application/json'\n\`\`\``,
      );
      out.push(``);
    }
  }

  return out.join("\n");
}


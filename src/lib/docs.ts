export function generateAdrDoc(project: ProjectSummary, adrs: Adr[]): string {
  const out: string[] = [];
  out.push(`# ${project.name} \u2014 Architecture Decision Records`);
  out.push(``);
  out.push(`> Generated by AI System Architect on ${formatDate(new Date().toISOString())}`);
  out.push(``);

  if (adrs.length === 0) {
    out.push(`No decision records have been created yet.`);
    return out.join("\n");
  }

  out.push(
    table(
      ["ID", "Title", "Status", "Tags", "Date"],
      adrs
        .slice()
        .sort((a, b) => a.number - b.number)
        .map((a) => [
          `ADR-${String(a.number).padStart(3, "0")}`,
          a.title,
          a.status,
          (a.tags ?? []).join(", ") || "\u2014",
          formatDate(a.created_at),
        ]),
    ),
  );
  out.push(``);
  out.push(`---`);
  out.push(``);

  for (const adr of adrs.slice().sort((a, b) => a.number - b.number)) {
    out.push(`## ADR-${String(adr.number).padStart(3, "0")}: ${adr.title}`);
    out.push(``);
    out.push(`- **Status:** ${adr.status}`);
    out.push(`- **Date:** ${formatDate(adr.created_at)}`);
    if ((adr.tags ?? []).length > 0) out.push(`- **Tags:** ${adr.tags.join(", ")}`);
    out.push(``);
    out.push(`### Context`);
    out.push(``);
    out.push(safe(adr.context, "_Not recorded._"));
    out.push(``);
    out.push(`### Decision`);
    out.push(``);
    out.push(safe(adr.decision, "_Not recorded._"));
    out.push(``);
    out.push(`### Consequences`);
    out.push(``);
    out.push(safe(adr.consequences, "_Not recorded._"));
    out.push(``);
    out.push(`### Alternatives considered`);
    out.push(``);
    out.push(safe(adr.alternatives, "_Not recorded._"));
    out.push(`---`);
    out.push(``);
  }

  return out.join("\n");
}

/* ------------------------------------------------------------------ */
/*  Mermaid diagram (embeddable in Markdown)                           */
/* ------------------------------------------------------------------ */

function mermaidId(label: string, index: number): string {
  return `n${index}_${label.replace(/[^a-zA-Z0-9]/g, "_").slice(0, 24)}`;
}

export function generateMermaid(diagram: Diagram, version: DiagramVersion): string {
  const { nodes, edges } = graphFromVersion(version);
  if (nodes.length === 0) return "```mermaid\ngraph TD\n  empty[No components yet]\n```\n";

  const lines: string[] = ["```mermaid", "graph LR"];

  nodes.forEach((node, i) => {
    const id = mermaidId(node.label, i);
    const label = node.label.replace(/"/g, "'").replace(/[\[\]()]/g, "");
    lines.push(`  ${id}["${label}"]`);
  });

  for (const edge of edges) {
    const si = nodes.findIndex((n) => n.id === edge.source);
    const ti = nodes.findIndex((n) => n.id === edge.target);
    if (si < 0 || ti < 0) continue;
    const from = mermaidId(nodes[si].label, si);
    const to = mermaidId(nodes[ti].label, ti);
    const arrow = edge.direction === "async" || edge.direction === "batch" ? "-.->" : "-->";
    const tag = [edge.protocol, edge.direction].filter(Boolean).join(" ");
    lines.push(`  ${from} ${arrow}|"${tag}"| ${to}`);
  }

  lines.push("```");
  return lines.join("\n");
}

